let current: Lang = (localStorage.getItem(STORAGE_KEY) as Lang | null) ?? "fa";

export function applyDocumentLang() {
  document.documentElement.lang = current;
  document.documentElement.dir = current === "fa" ? "rtl" : "ltr";
}

export const i18nProvider: I18nProvider = {
  translate: (key: string, options?: unknown) => {
    const text = messages[current][key] ?? key;
    const vars = (options ?? {}) as Record<string, unknown>;
    return text.replace(/\{(\w+)\}/g, (m, k: string) => {
      if (!(k in vars)) return m;
      const v = vars[k];
      // Numbers follow the UI language (Persian digits in fa).
      return typeof v === "number" ? new Intl.NumberFormat(current === "fa" ? "fa-IR" : "en-US").format(v) : String(v);
    });
  },
  getLocale: () => current,
  changeLocale: async (lang: string) => {
    current = lang === "en" ? "en" : "fa";
    localStorage.setItem(STORAGE_KEY, current);
    applyDocumentLang();
  },
};
